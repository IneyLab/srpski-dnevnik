/** Условие открытия: занятие отмечено выполненным, вся неделя пройдена или место открыто с самого начала. */
export type Unlock = { lesson: string } | { week: number } | 'start'

export interface Place {
  id: string
  /** Название по-сербски (кириллица). */
  sr: string
  /** Как по-русски. */
  ru: string
  lon: number
  lat: number
  /** Открывается, если выполнено ЛЮБОЕ из условий. */
  unlock: Unlock[]
  /** Связанный урок: неделя и занятие (slug) — ссылка с карточки места. */
  link: { week: number; slug?: string }
  /** Одна строка под названием. */
  tagline: string
  /** Культурная справка, 2–4 абзаца. */
  facts: string[]
}

